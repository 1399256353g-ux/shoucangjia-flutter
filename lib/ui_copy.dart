/// 在多处出现、且必须**逐字一致**的界面文案（唯一一份）。
///
/// 为什么要有这个文件：同一条文案在几个互不相邻的页面里各写一遍，改一处
/// 就分叉，而每一处单独看都「正常」。0.9.361 收的是两条：
///
/// | 文案 | 出现处 |
/// |---|---|
/// | 作者名输入框标签 | 作者页「新建作者」/ 基础库页 / 单元库挂载页「建作者目录」 |
/// | 挂载面板标题 | 作者主页挂载面板 / 单元库挂载页 / 单元库卡片按钮 tooltip |
///
/// 这两条都是「用户学习一次就该到处通用」的说法：三个入口建的是同一种
/// 目录（`@作者名`），两个面板打开的是同一份数据。措辞不同会让用户以为
/// 它们在干不同的事。
///
/// 注意：这里只放**跨页面复用**的文案。单页面里只出现一次的句子留在原处——
/// 把它们全搬进来会变成第二个「文案仓库」，反而看不出哪条是共用的。
library;

/// 新建作者目录时，名字输入框的标签。
///
/// 写清「会建成 @作者名 目录」是有意的：用户此前在作者页填了名字，
/// 回头在文件结构里看到一个带 `@` 的目录，认不出是自己建的。
const String kAuthorNameFieldLabel = '作者名（会建成 @作者名 目录）';

/// 「作者文件夹挂载」面板标题（作者主页 / 单元库页两个入口共用）。
const String kAuthorMountTitle = '作者文件夹挂载';

/// 「名称不能为空」：注册新库与建分类目录共用的校验措辞。
///
/// 两处校验的**语义不同**（一个是服务端注册库的 id/名称，一个是磁盘上的
/// 分类目录名），但用户看到的必须是同一句话——同一句校验出现两种说法，
/// 用户会以为其中一处要求更严。措辞归这里，判定逻辑各留各的。
const String kEmptyNameText = '名称不能为空';
